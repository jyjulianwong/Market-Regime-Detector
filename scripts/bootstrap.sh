#!/usr/bin/env bash
# One entry point for this repo's AWS account prerequisites, end to end:
#   1. applies terraform/bootstrap (Terraform state bucket, lock table and the
#      GitHub Actions OIDC role) into the account your AWS credentials resolve to;
#   2. moves the bootstrap's own state into that state bucket, so later runs
#      work from any clean clone;
#   3. sets the GitHub Actions secrets the deploy workflow needs, and deletes
#      the static access-key secrets OIDC replaces.
# Run it with admin credentials for the target account (e.g. after
# `aws sso login`). Safe to re-run: every step converges, and nothing is applied
# without showing you the plan and asking first.
#
# Usage: scripts/bootstrap.sh
set -euo pipefail

# --- Repo-specific settings ----------------------------------------------------
GITHUB_REPOSITORY="jyjulianwong/Market-Regime-Detector"
PROJECT="jyjulianwong-mrd" # terraform/bootstrap's var.project default
# The account-wide GitHub Actions OIDC provider is owned by
# jyjulianwong/Infrastructure-GitHub's bootstrap, which must run first.
OWNS_OIDC_PROVIDER=false
# Secrets the deploy workflow needs besides AWS_ACCOUNT_ID / AWS_ROLE_ARN. You're
# prompted for any the repo doesn't have yet; export one to overwrite it.
EXTRA_SECRETS=(FRED_API_KEY ALPHA_VANTAGE_API_KEY GH_ADMIN_TOKEN)
NEXT_STEPS="Next: merge this repo's OIDC migration PR. Its first deploy creates the ECR
repository, pushes the batch Lambda image and applies the whole main stack."
# --------------------------------------------------------------------------------

REGION="eu-west-2" # must match terraform/backend.tf and the workflows' AWS_REGION
OIDC_PROVIDER_HOST="token.actions.githubusercontent.com"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BOOTSTRAP_DIR="$ROOT/terraform/bootstrap"
BACKEND_FILE="$BOOTSTRAP_DIR/_backend.tf"
LOCAL_STATE="$BOOTSTRAP_DIR/terraform.tfstate"
WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

die() { echo "error: $*" >&2; exit 1; }
step() { printf '\n==> %s\n' "$*"; }
confirm() {
  local reply
  read -r -p "$1 [y/N] " reply
  [[ $reply =~ ^[Yy]$ ]] || die "aborted"
}
tf() { terraform -chdir="$BOOTSTRAP_DIR" "$@"; }

write_backend() {
  cat >"$BACKEND_FILE" <<EOF
# Generated by scripts/bootstrap.sh — do not commit.
terraform {
  backend "s3" {
    bucket         = "$STATE_BUCKET"
    key            = "bootstrap/terraform.tfstate"
    region         = "$REGION"
    dynamodb_table = "$LOCK_TABLE"
    encrypt        = true
  }
}
EOF
}

# Keeps (rather than deletes) the local copy once it lives in S3, under a name
# every repo's .gitignore already covers (*.tfstate).
retire_local_state() {
  local suffix
  suffix="$(date +%Y%m%d%H%M%S)"
  [[ -f $LOCAL_STATE ]] && mv "$LOCAL_STATE" "$BOOTSTRAP_DIR/migrated-$suffix.tfstate"
  [[ -f $LOCAL_STATE.backup ]] && mv "$LOCAL_STATE.backup" "$BOOTSTRAP_DIR/migrated-$suffix.backup.tfstate"
  return 0
}

# --- 1. Preflight -------------------------------------------------------------------
step "Preflight"
for cmd in aws terraform gh jq; do
  command -v "$cmd" >/dev/null || die "$cmd is not installed"
done
IDENTITY="$(aws sts get-caller-identity --output json)" \
  || die "no working AWS credentials — run \`aws sso login\` (or export credentials for the target account) first"
ACCOUNT_ID="$(jq -r .Account <<<"$IDENTITY")"
gh auth status >/dev/null 2>&1 || die "gh is not authenticated — run \`gh auth login\` first"

STATE_BUCKET="$ACCOUNT_ID-$PROJECT-terraform-state"
LOCK_TABLE="$PROJECT-terraform-lock"

echo "  GitHub repository: $GITHUB_REPOSITORY"
echo "  AWS account:       $ACCOUNT_ID ($(jq -r .Arn <<<"$IDENTITY"))"
echo "  AWS region:        $REGION"
confirm "Bootstrap $GITHUB_REPOSITORY into AWS account $ACCOUNT_ID?"

if [[ $OWNS_OIDC_PROVIDER != true ]]; then
  aws iam get-open-id-connect-provider \
    --open-id-connect-provider-arn "arn:aws:iam::$ACCOUNT_ID:oidc-provider/$OIDC_PROVIDER_HOST" >/dev/null 2>&1 \
    || die "account $ACCOUNT_ID has no GitHub Actions OIDC provider yet — run jyjulianwong/Infrastructure-GitHub's scripts/bootstrap.sh first"
fi

# A local state file left over from the pre-OIDC, local-state bootstrap (or one
# for another account) must never be applied or migrated into this account.
if [[ -f $LOCAL_STATE ]]; then
  local_bucket="$(jq -r '[(.resources // [])[] | select(.type == "aws_s3_bucket") | .instances[0].attributes.bucket][0] // empty' "$LOCAL_STATE")"
  if [[ $local_bucket != "$STATE_BUCKET" ]]; then
    aside="$BOOTSTRAP_DIR/stale-$(date +%Y%m%d%H%M%S).tfstate"
    mv "$LOCAL_STATE" "$aside"
    echo "  Moved unrelated local state (${local_bucket:-no resources}) aside to $(basename "$aside")"
  fi
fi

# --- 2. Terraform init: S3 backend if it exists yet, local state otherwise ----------
step "Initialising terraform/bootstrap"
if aws s3api head-bucket --bucket "$STATE_BUCKET" >/dev/null 2>&1 \
  && aws dynamodb describe-table --region "$REGION" --table-name "$LOCK_TABLE" >/dev/null 2>&1; then
  write_backend
  if [[ -f $LOCAL_STATE ]]; then
    # An earlier run applied but stopped before migrating. Interactive on
    # purpose: Terraform asks before overwriting any state already in S3.
    tf init -migrate-state
    retire_local_state
  else
    tf init -input=false -reconfigure
  fi
else
  rm -f "$BACKEND_FILE"
  tf init -input=false -reconfigure
fi

# --- 3. Plan and apply -----------------------------------------------------------------
step "Planning terraform/bootstrap"
TF_VARS=(
  -var "aws_account_id=$ACCOUNT_ID"
  -var "aws_region=$REGION"
  -var "github_repository=$GITHUB_REPOSITORY"
)
plan_rc=0
tf plan -input=false -detailed-exitcode "${TF_VARS[@]}" -out="$WORK_DIR/bootstrap.tfplan" || plan_rc=$?
case $plan_rc in
  0) echo "  Already up to date" ;;
  2)
    confirm "Apply this plan to account $ACCOUNT_ID?"
    tf apply -input=false "$WORK_DIR/bootstrap.tfplan"
    ;;
  *) die "terraform plan failed" ;;
esac

if [[ ! -f $BACKEND_FILE ]]; then
  step "Moving bootstrap state into s3://$STATE_BUCKET"
  write_backend
  # The bucket was created by the apply above, so there is no remote state to
  # overwrite.
  tf init -input=false -migrate-state -force-copy
  retire_local_state
fi

ROLE_ARN="$(tf output -raw github_actions_role_arn)"

# --- 4. GitHub Actions secrets -----------------------------------------------------------
step "Setting GitHub Actions secrets on $GITHUB_REPOSITORY"
set_secret() { printf '%s' "$2" | gh secret set "$1" --repo "$GITHUB_REPOSITORY"; }

set_secret AWS_ACCOUNT_ID "$ACCOUNT_ID"
set_secret AWS_ROLE_ARN "$ROLE_ARN"
echo "  Set AWS_ACCOUNT_ID and AWS_ROLE_ARN"

EXISTING_SECRETS="$(gh secret list --repo "$GITHUB_REPOSITORY" --limit 200 --json name --jq '.[].name')"
# ${arr[@]+...} keeps empty arrays safe under `set -u` on macOS's bash 3.2.
for name in ${EXTRA_SECRETS[@]+"${EXTRA_SECRETS[@]}"}; do
  if [[ -n ${!name:-} ]]; then
    set_secret "$name" "${!name}"
    echo "  Set $name (from your environment)"
  elif grep -qx "$name" <<<"$EXISTING_SECRETS"; then
    echo "  $name already set — export $name to overwrite it"
  else
    value=""
    read -r -s -p "  $name is not set yet — paste its value (hidden): " value || true
    echo
    [[ -n $value ]] || die "$name is required by the deploy workflow"
    set_secret "$name" "$value"
    echo "  Set $name"
  fi
done

for name in AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY; do
  if grep -qx "$name" <<<"$EXISTING_SECRETS"; then
    gh secret delete "$name" --repo "$GITHUB_REPOSITORY"
    echo "  Deleted $name (replaced by OIDC)"
  fi
done

# --- Repo-specific extra steps (optional repo_post_bootstrap in the settings) --------------
if declare -F repo_post_bootstrap >/dev/null; then
  repo_post_bootstrap
fi

# --- Done ------------------------------------------------------------------------------------
step "Bootstrapped $GITHUB_REPOSITORY into AWS account $ACCOUNT_ID"
echo "  State bucket: s3://$STATE_BUCKET"
echo "  Lock table:   $LOCK_TABLE"
echo "  CI role:      $ROLE_ARN"
echo
echo "$NEXT_STEPS"
